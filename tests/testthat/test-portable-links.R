test_that("link checks do not rely on the Windows readlink stub", {
  root <- withr::local_tempdir()
  outside <- withr::local_tempdir()
  writeLines("external evidence", file.path(outside, "source.txt"))
  writeLines("ordinary", file.path(root, "regular.txt"))
  links <- file.path(root, c("file-link", "directory-link", "dangling-link"))
  targets <- c(file.path(outside, "source.txt"), outside, file.path(outside, "absent"))
  linked <- suppressWarnings(file.symlink(targets, links))
  withr::defer(fs::link_delete(links[fs::is_link(links)]))
  if (!all(linked)) skip("This platform does not permit the required symbolic links")
  local_mocked_bindings(Sys.readlink = function(paths) rep("", length(paths)), .package = "base")
  expect_identical(.cs_is_link(c(file.path(root, "regular.txt"), root,
    file.path(root, "missing"), links)), c(FALSE, FALSE, FALSE, TRUE, TRUE, TRUE))
  expect_false(.cs_regular_member(root, "file-link"))
  expect_false(.cs_regular_member(root, "directory-link/source.txt"))
  expect_false(.cs_regular_member(root, "dangling-link"))
  members <- .cs_directory_members(root)
  expect_true(all(basename(links) %in% members))
  expect_false("directory-link/source.txt" %in% members)
  expect_identical(readLines(file.path(outside, "source.txt")), "external evidence")
})

test_that("linked write destinations preserve their targets", {
  root <- withr::local_tempdir()
  outside <- file.path(root, "canonical")
  cs_write(cs_example(), outside, format = "tsv.gz")
  before <- readBin(file.path(outside, "MANIFEST.sha256"), "raw", n = 100000L)
  alias <- file.path(root, "alias")
  if (!suppressWarnings(file.symlink(outside, alias))) skip("Symbolic links unavailable")
  withr::defer(fs::link_delete(alias))
  local_mocked_bindings(Sys.readlink = function(paths) rep("", length(paths)), .package = "base")
  expect_error(cs_write(cs_example(), alias, format = "tsv.gz", overwrite = TRUE),
    class = "cellspec_error_format")
  expect_identical(readBin(file.path(outside, "MANIFEST.sha256"), "raw", n = 100000L), before)
  expect_true(all(cs_verify(outside)$ok))
})

test_that("Windows junction members are not traversed", {
  skip_if_not(.Platform$OS.type == "windows", "Windows junction check")
  root <- withr::local_tempdir()
  outside <- withr::local_tempdir()
  writeLines("keep", file.path(outside, "source.txt"))
  junction <- file.path(root, "junction")
  expect_true(Sys.junction(outside, junction))
  withr::defer(fs::link_delete(junction))
  expect_true(.cs_is_link(junction))
  expect_identical(.cs_directory_members(root), "junction")
  expect_false(.cs_regular_member(root, "junction/source.txt"))
  expect_identical(readLines(file.path(outside, "source.txt")), "keep")
})

test_that("overwrite refuses a linked sidecar before parsing it", {
  x <- cs_example()
  root <- withr::local_tempdir()
  path <- file.path(root, "canonical")
  cs_write(x, path, format = "tsv.gz")
  outside <- file.path(root, "external.json")
  writeLines('{"format":"cellspec","review":"keep"}', outside)
  sidecar <- file.path(path, "cellspec.json")
  unlink(sidecar)
  if (!suppressWarnings(file.symlink(outside, sidecar))) skip("Symbolic links unavailable")
  withr::defer(fs::link_delete(sidecar))
  from_json <- jsonlite::fromJSON
  parsed <- character()
  local_mocked_bindings(fromJSON = function(txt, ...) {
    parsed <<- c(parsed, txt)
    from_json(txt, ...)
  }, .package = "jsonlite")
  expect_error(cs_write(x, path, format = "tsv.gz", overwrite = TRUE),
    class = "cellspec_error_format")
  expect_length(parsed, 0L)
  expect_identical(readLines(outside), '{"format":"cellspec","review":"keep"}')
})
